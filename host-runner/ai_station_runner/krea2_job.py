"""One offline, fixed Krea invocation in the native Runner's owned process group.

This directly imports the pinned owned runtime, like the existing Wan job. It
starts no Comfy server, accepts no arbitrary workflow and controls no external UI.
Configuration is generated by the native adapter, never supplied as an HTTP graph.
"""

import importlib.util
import json
import os
import resource
import signal
import sys
from pathlib import Path

from ai_station_runner.krea2 import (
    KreaFile,
    KreaOptions,
    gpu_only_args,
    require_gpu_placement,
    require_loaded_gpu_weights,
)


def stage(message):
    print(f"image.stage: {message}", flush=True)


def load_plugin(path, name):
    spec = importlib.util.spec_from_file_location(
        name, Path(path) / "__init__.py", submodule_search_locations=[str(path)]
    )
    if spec is None or spec.loader is None:
        raise ValueError("Configured Krea plugin is unavailable")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def main(config_path):
    config = json.loads(Path(config_path).read_text())
    request = KreaOptions.model_validate(config["request"])
    request.validate_references(len(config["inputs"]))
    # Hashes precede imports/inference, including the operator's chosen checkpoint.
    stage("verifying selected weights")
    files = {role: KreaFile.model_validate(item).verify() for role, item in config["files"].items()}
    role = request.lora_role()
    if set(files) != {"model", "encoder", "vae", *([role] if role else [])}:
        raise ValueError("Krea files do not match the selected operation")
    signal.alarm(3600)
    sys.path.insert(0, config["runtime"]["comfy"])
    sys.argv = gpu_only_args(config["work"])
    import comfy.options

    comfy.options.enable_args_parsing()
    import comfy.model_management as memory
    import folder_paths
    import nodes
    import numpy as np
    import torch
    from comfy_extras.nodes_sd3 import EmptySD3LatentImage
    from PIL import Image, ImageOps

    count = torch.cuda.device_count()
    if count != config["gpu_count"] or count not in {1, 2}:
        raise ValueError("Visible GPUs do not match the reserved Krea devices")
    auxiliary = count - 1
    # CUDA_VISIBLE_DEVICES is set by the native adapter to precisely the reserved
    # physical devices. These are process-local indexes, never host indexes.
    torch.cuda.set_device(auxiliary)
    edit = load_plugin(config["runtime"]["edit"], "ai_station_krea2edit") if role else None
    gguf = load_plugin(config["runtime"]["gguf"], "ai_station_krea2gguf")
    aliases = {}
    for file_role, file in files.items():
        category = {"model": "diffusion_models", "encoder": "text_encoders", "vae": "vae"}.get(
            file_role, "loras"
        )
        directory = Path(config["work"]) / "selected_models" / category
        directory.mkdir(parents=True, exist_ok=True)
        alias = directory / (file_role + file.suffix)
        alias.symlink_to(file)
        aliases[file_role] = alias.name
        folder_paths.folder_names_and_paths[category] = ([str(directory)], {".safetensors", ".gguf"})
    # The GGUF plugin reads `unet`; no other installed model directory is exposed.
    folder_paths.folder_names_and_paths["unet"] = folder_paths.folder_names_and_paths["diffusion_models"]
    images = []
    for observation in config["inputs"]:
        file = KreaFile.model_validate(observation).verify()
        with Image.open(file) as source:
            pixels = ImageOps.exif_transpose(source).convert("RGB")
            # Preserve aspect ratio, while avoiding an unnecessary full-resolution
            # VAE allocation for a large uploaded photo before the target fit.
            side = max(request.width, request.height, request.grounding_px)
            pixels.thumbnail((side, side), Image.Resampling.LANCZOS)
            images.append(torch.from_numpy(np.array(pixels, dtype=np.float32) / 255).unsqueeze(0))
    with torch.inference_mode():
        stage("encoding instruction on GPU")
        clip = nodes.CLIPLoader().load_clip(aliases["encoder"], "krea2", "default")[0]
        require_gpu_placement(clip.patcher, auxiliary)
        memory.load_models_gpu([clip.patcher], force_full_load=True)
        require_loaded_gpu_weights(clip.patcher, auxiliary)
        if role:
            positive = edit.Krea2EditGroundedEncode().encode(
                clip, request.prompt, images[0], images[1] if len(images) > 1 else None, request.grounding_px
            )[0]
            negative = edit.Krea2EditGroundedEncode().encode(
                clip,
                request.negative,
                images[0],
                images[1] if len(images) > 1 else None,
                request.grounding_px,
            )[0]
        else:
            positive = nodes.CLIPTextEncode().encode(clip, request.prompt)[0]
            negative = nodes.CLIPTextEncode().encode(clip, request.negative)[0]
        stage("encoding references on GPU")
        vae = nodes.VAELoader().load_vae(aliases["vae"])[0]
        require_gpu_placement(vae.patcher, auxiliary)
        memory.load_models_gpu([vae.patcher], force_full_load=True)
        require_loaded_gpu_weights(vae.patcher, auxiliary)
        sources = [nodes.VAEEncode().encode(vae, image)[0] for image in images]
        torch.cuda.set_device(0)
        latent = EmptySD3LatentImage.execute(request.width, request.height, 1)[0]
        stage("loading diffusion model on GPU")
        if files["model"].suffix == ".gguf":
            model = gguf.NODE_CLASS_MAPPINGS["UnetLoaderGGUF"]().load_unet(
                aliases["model"], dequant_dtype="target", patch_dtype="target", patch_on_device=True
            )[0]
        else:
            model = nodes.UNETLoader().load_unet(aliases["model"], "default")[0]
        require_gpu_placement(model, 0)
        if role:
            model = nodes.LoraLoaderModelOnly().load_lora_model_only(model, aliases[role], 1.0)[0]
            # Pre-encode at target size before loading/sampling the diffusion model.
            # VAE stays on the auxiliary GPU, never falls back to CPU.
            torch.cuda.set_device(auxiliary)
            model = edit.Krea2EditModelPatch().patch(
                model,
                sources[0],
                source_latent_b=sources[1] if len(sources) > 1 else None,
                vae=vae,
                source_image=images[0],
                source_image_b=images[1] if len(images) > 1 else None,
                target_latent=latent,
                fit_mode="fit",
                ref_boost=request.reference_strength,
                ref_boost_a=request.reference_strength,
                ref_position="aligned (trained)"
                if request.reference_layout == "aligned"
                else "beside (right of target)",
                ref_position_a="aligned (trained)",
            )[0]
            torch.cuda.set_device(0)
        require_gpu_placement(model, 0)
        memory.load_models_gpu([model], force_full_load=True)
        require_loaded_gpu_weights(model, 0)
        stage("generating image on GPU")
        samples = nodes.KSampler().sample(
            model, request.seed, request.steps, request.cfg, "euler", "simple", positive, negative, latent
        )[0]
        torch.cuda.set_device(auxiliary)
        stage("decoding image on GPU")
        memory.load_models_gpu([vae.patcher], force_full_load=True)
        require_loaded_gpu_weights(vae.patcher, auxiliary)
        frames = nodes.VAEDecode().decode(vae, samples)[0]
        if tuple(frames.shape[:3]) != (1, request.height, request.width) or not torch.isfinite(frames).all():
            raise ValueError("Krea decoded output does not match the requested image")
        # Only final pixels cross back to CPU for PNG serialization.
        pixels = (frames[0].clamp(0, 1).cpu().numpy() * 255).round().astype(np.uint8)
        output = Path(config["output"])
        partial = output.with_name(output.name + ".partial")
        Image.fromarray(pixels).save(partial, format="PNG")
        with Image.open(partial) as image:
            image.verify()
        partial.replace(output)
        output.with_suffix(".json").write_text(
            json.dumps(
                {
                    "cpu_offload": False,
                    "fully_resident_cuda_weights_checked": True,
                    "gpu_uuids": os.environ.get("CUDA_VISIBLE_DEVICES", "").split(","),
                    "gpu_memory": [
                        {
                            "logical_index": index,
                            "peak_allocated_bytes": torch.cuda.max_memory_allocated(index),
                            "peak_reserved_bytes": torch.cuda.max_memory_reserved(index),
                            "total_bytes": torch.cuda.get_device_properties(index).total_memory,
                        }
                        for index in range(count)
                    ],
                    "peak_process_rss_kib": resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
                    "preset": request.model_dump(),
                },
                indent=2,
            )
            + "\n"
        )
        stage("completed")


if __name__ == "__main__":
    main(sys.argv[1])
